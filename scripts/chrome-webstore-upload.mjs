import { createSign } from 'node:crypto';
import { readFileSync } from 'node:fs';

const zipPath = process.argv[2];
const id = process.env.CHROME_EXTENSION_ID;
const publisher = process.env.CHROME_PUBLISHER_ID;
const raw = process.env.CHROME_SERVICE_ACCOUNT_JSON;
if (!zipPath || !id || !publisher || !raw) throw new Error('Chrome upload requires ZIP path, CHROME_PUBLISHER_ID, CHROME_EXTENSION_ID, and CHROME_SERVICE_ACCOUNT_JSON.');
const account = JSON.parse(raw);
const b64 = (value) => Buffer.from(value).toString('base64url');
const now = Math.floor(Date.now() / 1000);
const header = b64(JSON.stringify({ alg: 'RS256', typ: 'JWT' }));
const payload = b64(JSON.stringify({ iss: account.client_email, scope: 'https://www.googleapis.com/auth/chromewebstore', aud: 'https://oauth2.googleapis.com/token', iat: now, exp: now + 3600 }));
const signer = createSign('RSA-SHA256'); signer.update(`${header}.${payload}`);
const assertion = `${header}.${payload}.${b64(signer.sign(account.private_key))}`;
const tokenResponse = await fetch('https://oauth2.googleapis.com/token', { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ grant_type: 'urn:ietf:params:oauth:grant-type:jwt-bearer', assertion }) });
if (!tokenResponse.ok) throw new Error(`Chrome auth failed before upload: HTTP ${tokenResponse.status}`);
const { access_token: token } = await tokenResponse.json();
const uploadResponse = await fetch(`https://chromewebstore.googleapis.com/upload/v2/publishers/${encodeURIComponent(publisher)}/items/${encodeURIComponent(id)}:upload`, { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/zip' }, body: readFileSync(zipPath) });
if (!uploadResponse.ok) throw new Error(`Chrome upload failed: HTTP ${uploadResponse.status} ${await uploadResponse.text()}`);
const result = await uploadResponse.json();
console.log(JSON.stringify({ uploadState: result.uploadState, itemId: result.itemId ?? id }, null, 2));
if (result.uploadState && !['SUCCESS', 'SUCCEEDED'].includes(result.uploadState)) process.exitCode = 1;
